#include <stdio.h>

int main(){
    // a, c, e คือตัวอักษรลำดับที่ 1, 3, 5 (จะถูกแปลงเป็นตัวถัดไป)
    // b, d คือตัวอักษรลำดับที่ 2, 4 (ไม่ต้องแปลง ปล่อยผ่านตามเดิม)
    char a;
    char b;
    char c;
    char d;
    char e;

    // เก็บผลลัพธ์หลังแปลง (a+1, c+1, e+1) แยกจากตัวแปรเดิม
    // ประกาศเป็น int เพราะผลบวก char+1 ใน C จะถูก promote เป็น int โดยอัตโนมัติ
    int inp1;
    int inp3;
    int inp5;

    // scanf ตัวแรก (&a) ไม่ต้องเว้นวรรคนำหน้า เพราะเป็น input ตัวแรกสุด บัฟเฟอร์ยังไม่มี \n ค้างอยู่
    // ส่วน scanf ตัวถัดๆ ไป ต้องเว้นวรรคหน้า %c เสมอ เพื่อข้าม \n ที่ค้างจาก Enter ของบรรทัดก่อนหน้า
    // (%c ไม่ข้าม whitespace ให้อัตโนมัติเหมือน %s/%d จึงต้องเว้นวรรคดักไว้เอง)
    scanf("%c", &a);
    scanf(" %c", &b);
    scanf(" %c", &c);
    scanf(" %c", &d);
    scanf(" %c", &e);

    // แปลงตัวอักษรลำดับที่ 1, 3, 5 ให้เป็นตัวถัดไปในลำดับ ASCII (เช่น 'a' -> 'b', 'x' -> 'y')
    inp1 = a+1;
    inp3 = c+1;
    inp5 = e+1;

    // พิมพ์ด้วย %c เพื่อแสดงเป็นตัวอักษรตามโจทย์ (แม้ inp1/inp3/inp5 เป็น int แต่ %c จะแปลงกลับเป็นตัวอักษรให้)
    // เรียงลำดับพิมพ์ตามตำแหน่งเดิม: แปลง, ไม่แปลง, แปลง, ไม่แปลง, แปลง
    printf("%c\n",inp1);
    printf("%c\n",b);
    printf("%c\n",inp3);
    printf("%c\n",d);
    printf("%c\n",inp5);

    return 0;
}
#include <stdio.h>

int main(){
    char fname1[30];
    char sname1[30];
    char person2[30];
    char person3[30];

    // %s หยุดอ่านทันทีที่เจอช่องว่างใดๆ (space, tab, \n) จึงรับได้แค่ "คำเดียว" ไม่รับชื่อที่มีเว้นวรรค
    // และ %s จะข้าม whitespace ที่ค้างอยู่ก่อนหน้าให้อัตโนมัติ ก่อนเริ่มอ่านคำถัดไป
    scanf("%s", fname1);
    scanf("%s", sname1);

    // %[^\n] คือ scanset: อ่านตัวอักษรอะไรก็ได้ (รวมช่องว่างกลางคำ) ไปเรื่อยๆ
    // จนกว่าจะเจอ \n เท่านั้น จึงรับ input ที่มีเว้นวรรคทั้งบรรทัดได้ เช่น "Thatchakorn Bunnin"
    //
    // แต่ %[^\n] ต่างจาก %s ตรงที่ "ไม่ข้าม whitespace ให้อัตโนมัติ"
    // หลังจาก scanf("%s", sname1) กดใส่ input แล้วยังมี \n ตัวสุดท้ายค้างอยู่ใน buffer เสมอ
    // ถ้าเรียก scanf("%[^\n]", person2) ตรงๆ มันจะเจอ \n ค้างนั้นทันที แล้วอ่านได้ string ว่างเปล่า
    //
    // ทางแก้คือใส่ช่องว่างนำหน้า " %[^\n]" เพราะช่องว่างใน format string ของ scanf
    // หมายถึง "ข้าม whitespace ทุกชนิด (space/tab/\n) ที่ค้างอยู่ให้หมดก่อน" แล้วค่อยเริ่มอ่านจริง
    scanf(" %[^\n]", person2);
    scanf(" %[^\n]", person3);


    printf("Person 1: %s %s\n",fname1,sname1);
    printf("Person 2: %s\n",person2);
    printf("Person 3: %s\n",person3);

    return 0;
}

